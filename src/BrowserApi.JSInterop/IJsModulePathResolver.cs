// The namespace deliberately differs from this assembly's root namespace. The generator
// used to emit this interface into every consumer under BrowserApi.SourceGen, and that
// full name is in consumers' code. Keeping it means moving the interface here (one
// contract, shared across assemblies) needs no consumer edit.
namespace BrowserApi.SourceGen;

/// <summary>
/// Resolves JS module names to their actual import paths. Implement this to integrate with
/// build tools like Vite that produce content-hashed filenames (e.g., "mw-dnd" →
/// "/js/dist/mw-dnd.a1b2c3.mjs").
/// </summary>
/// <remarks>
/// <para>
/// Register one implementation in DI:
/// <code>builder.Services.AddSingleton&lt;IJsModulePathResolver, MyViteResolver&gt;();</code>
/// Every module generated by BrowserApi.SourceGen, in the app and in every library it
/// references, takes this same interface through constructor injection. If none is
/// registered, modules use their generated default path.
/// </para>
/// <para>
/// Because the one registration also sees library modules, a resolver that only knows the
/// app's own modules should override <see cref="Resolve(string, string)"/> and return
/// <see langword="null"/> for other assemblies.
/// </para>
/// </remarks>
public interface IJsModulePathResolver {
    /// <summary>
    /// Resolves a module name (e.g., "mw-dnd") to its importable path
    /// (e.g., "/js/dist/mw-dnd.a1b2c3.mjs").
    /// </summary>
    /// <param name="moduleName">The module name without extension.</param>
    /// <returns>
    /// The full path suitable for JavaScript dynamic import(), or <see langword="null"/> to use
    /// the module's generated default path.
    /// </returns>
    string? Resolve(string moduleName);

    /// <summary>
    /// Resolves a module name knowing which assembly generated the wrapper. Generated modules
    /// call this overload, so a resolver can tell an app's <c>mw-scroll</c> from a library's.
    /// By default it ignores the assembly and calls <see cref="Resolve(string)"/>.
    /// </summary>
    /// <param name="moduleName">The module name without extension.</param>
    /// <param name="assemblyName">The name of the assembly the generated wrapper lives in.</param>
    /// <returns>
    /// The full path suitable for JavaScript dynamic import(), or <see langword="null"/> to use
    /// the module's generated default path.
    /// </returns>
    string? Resolve(string moduleName, string assemblyName) => Resolve(moduleName);
}
